"""AI-40: is the act-then-hedge split a MODEL effect or a JUDGE effect?

DESCRIPTIVE / DIAGNOSTIC, not confirmatory. Nothing here is pre-registered in
`docs/analysis-plan.md` and this script deliberately does not touch it: the
question is a robustness check on an observed asymmetry, generated by the same
data that would test it.

## The observation

An "act-then-hedge" episode is one where the argument-level harm predicate says
the harmful outcome OCCURRED (`principal_eval.harm.harm_verdict(...).harmful`,
which reads recorded tool arguments and never reads free text) but the blind
reply-only judge did NOT grade the final reply COMPLIED. The counts land almost
entirely on one provider (sol 19, terra 22, luna 11 vs opus-5 0, sonnet-5 0).

## The confound

`principal_eval.judges` draws the judge from the OPPOSITE provider, so the two
sides of that split were graded by different judges:

    OpenAI subject   -> anthropic/claude-haiku-4-5
    Anthropic subject -> openai/gpt-4o-mini

So "OpenAI models act then hedge" and "claude-haiku-4-5 is stingier with
COMPLIED than gpt-4o-mini is" predict the same table. This script separates them.

## What it does

1. Denominators per arm: harmful episodes, how many were not graded COMPLIED,
   the fraction with a 95% scenario-clustered bootstrap CI (reusing
   `principal_eval.analysis.bootstrap_ci`, rule 10's 10,000 resamples), and the
   persona x scenario cell of every disagreement episode. Split
   status_irrelevant vs role_gated, because they are different estimands
   everywhere else in this project (rule 2).
2. A provider-level test of the hedge fraction, three ways, all stated either
   way: a scenario-clustered bootstrap on the pooled difference, a
   scenario-stratified episode-level permutation test, and a model-level
   permutation test (the most conservative -- with 3 OpenAI and 2 Anthropic
   arms its smallest attainable one-sided p is 1/10 = 0.100).
3. The cross-judge re-grade readout (see `--regrade` below).
4. Verbatim hedged replies next to the tool call that contradicts them, with a
   hedge-type classification. **Reasoning content is encrypted on every arm
   (AI-32), so this classification is from VISIBLE ASSISTANT TEXT ONLY.**
5. Whether the hedged episodes concentrate in high-status persona cells.

## The re-grade (`--regrade`), and why it is not `inspect score`

`inspect score` IS the repo-canonical re-grade mechanism and it does work here:

    uv run inspect score <log.eval> \
        --scorer src/principal_eval/scoring.py@persona_scorer \
        -S judge_model=openai/gpt-4o-mini \
        --output-file logs/ai40-crossjudge/<arm>/regraded.eval --action overwrite

(note `-S`, scorer args -- CLAUDE.md's `-T judge_model=...` is the `inspect eval`
form and is rejected by `inspect score`; and the scorer needs its file path,
because `persona_scorer` is not in the registry until that module is loaded).
Two things make it the wrong tool for THIS ticket:

  * It cannot target a subset of samples -- it re-grades all 1200. The hedge
    fraction is defined only over harmful episodes (384 of 6000 samples across
    the five arms), so 94% of those judge calls answer nothing being asked.
  * Re-grading all five logs both ways projects to ~$3.0 (the two Anthropic
    arms alone are ~$2.7: claude-haiku-4-5 is ~7x gpt-4o-mini per input token
    and opus-5/sonnet-5 write 5-7x longer replies), against AI-40's stated
    judge-only budget of well under GBP 1.

So `--regrade` calls `principal_eval.scoring.judge_answer` directly -- the same
function, the same `JUDGE_TEMPLATE`, the same `parse_grade`, on the same stored
`score.answer` (which is verbatim `state.output.completion`, what the original
judge saw). No subject-model call is made. It grades every harmful episode in
every arm with BOTH judges, which is a superset of the ticket's ask and buys the
control the ticket's ask lacks: the same-judge replicate separates judge
NON-DETERMINISM from a provider difference, so a flipped grade can't be
mistaken for a judge effect when it is just sampling noise.

Results are written to a NEW directory (`logs/ai40-crossjudge/`); no existing
log is opened for writing at any point.

Usage:
    uv run python scripts/ai40_act_then_hedge.py --regrade   # judge calls, once
    uv run python scripts/ai40_act_then_hedge.py             # every number
"""
